#!/usr/bin/env node
// scripts/emit-version-dates.mjs — when did each version actually land on main?
//
// Chad: "I want date and times those prs merged."
//
// WHY THE ROLLBACK PANEL NEEDS THIS. The panel lists versions and what each one would undo, but
// nothing in the bundle knows WHEN a past version shipped — VERSION_LOG rows are two-element and
// public/version.json carries only the current build's stamp. Chad does not think in version
// numbers, he thinks in wall clock: "roll the app back to 11:59 pm sept 14th". Without a date
// beside each row the panel cannot answer the question he actually asks it.
//
// WHERE THE DATE COMES FROM: the commit that moved APP_VERSION. `git log -L` on that one line
// gives exactly the commits that changed it, so the stamp is when the version LANDED ON MAIN —
// not when somebody typed it, and not the build time. Those differ: public/version.json's `at`
// is `new Date()` at build, and reusing it would put a plausible wrong time beside a button that
// changes production, which is the species of confident-wrong-number this feature exists to kill.
//
// IT MERGES, IT NEVER TRUNCATES, AND IT NEVER FAILS THE BUILD. Three deliberate properties:
//
//   MERGE — the output file is COMMITTED and this only ever adds to it. Nothing in this repo
//     says whether the Netlify build image has a git binary, whether .git is present, or how
//     deep the clone is; the only depth statement anywhere is `fetch-depth: 0` in GitHub
//     Actions, which governs CI and not deploys, and vite.config.js reads COMMIT_REF from env
//     rather than shelling out to git — which is evidence the build was written NOT to depend
//     on git. I cannot tell from the repo which way it goes. So a shallow clone, or no git at
//     all, leaves the committed map exactly as it was instead of overwriting it with a stub.
//   NEVER EXIT NON-ZERO — deliberately unlike emit-version-json.mjs, which exits 1 when it
//     cannot find APP_VERSION. A missing date is a cosmetic gap on one row. It must never be
//     the reason a deploy fails on the morning somebody is trying to roll back.
//   FIRST LANDING WINS — a version string can appear twice (v1.37.1 shipped on both a56050b
//     and a376d9a, two branches claiming one number). The first time it reached main is the
//     honest answer to "when did this land"; taking the last would date a version by a later
//     accident. Written down here because it is a rule, not an implementation detail.
//
// A VERSION CAN HAVE NO DATE AND THAT IS CORRECT. v1.40.0 has a changelog row but never existed
// as a running APP_VERSION: d412457 moved the line 1.39.0 → 1.41.0 in a single commit while its
// subject said (v1.40.0). No git method can date it, and the panel prints nothing rather than
// borrowing a neighbour's time.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'src', 'lib', 'version-dates.js');
const TRACKED = 'dispatch-map/src/App.jsx';

/** PURE: parse the `git log -L` stream into {version -> epochSeconds}, FIRST landing wins. */
export function parseVersionLog(stream) {
  const out = {};
  let at = null;
  for (const line of String(stream || '').split('\n')) {
    const meta = /^COMMIT([0-9a-f]+)(\d+)$/.exec(line);
    if (meta) { at = Number(meta[2]); continue; }
    const bump = /^\+const APP_VERSION = '(\d+\.\d+\.\d+)'/.exec(line);
    // `git log` walks newest-first, so the LAST assignment seen for a version is the EARLIEST
    // one — overwrite unconditionally and the first landing is what survives.
    if (bump && Number.isFinite(at) && at > 0) out[bump[1]] = at;
  }
  return out;
}

/** PURE: the module text. Sorted by version so the diff is readable when it is committed. */
export function renderModule(map) {
  const rows = Object.entries(map)
    .sort((a, b) => cmp(b[0], a[0]))
    .map(([v, secs]) => `  '${v}': '${new Date(secs * 1000).toISOString()}',`)
    .join('\n');
  return `// GENERATED by scripts/emit-version-dates.mjs — do not edit by hand.
//
// When each APP_VERSION landed on main, read off the commit that moved the line. Committed on
// purpose: the generator MERGES into this file and never truncates it, so a build where git is
// unavailable or the clone is shallow keeps these rather than replacing them with a stub.
//
// A version missing from this map renders with no date, which is the honest answer. v1.40.0 is
// the standing example — it has a changelog row but never existed as a running APP_VERSION.
export const VERSION_DATES = {
${rows}
};
`;
}

function cmp(a, b) {
  const pa = String(a).split('.').map(Number); const pb = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) - (pb[i] || 0);
  return 0;
}

/** The map already committed, so a git-less build keeps what it had. */
function existing() {
  try {
    const src = readFileSync(OUT, 'utf8');
    const out = {};
    for (const m of src.matchAll(/'(\d+\.\d+\.\d+)':\s*'([^']+)'/g)) {
      const t = Date.parse(m[2]);
      if (Number.isFinite(t)) out[m[1]] = Math.floor(t / 1000);
    }
    return out;
  } catch { return {}; }
}

function fromGit() {
  try {
    const stream = execFileSync('git', [
      'log', '-L', `/^const APP_VERSION = /,+1:${TRACKED}`, '--format=COMMIT%H%ct',
    ], { cwd: path.resolve(root, '..'), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
    return parseVersionLog(stream);
  } catch {
    return null;   // no git, no .git, shallow graft, wrong cwd — all the same answer here
  }
}

export function main() {
  const have = existing();
  const got = fromGit();
  if (got === null) {
    console.log(`emit-version-dates: git could not answer — keeping the ${Object.keys(have).length} committed date(s)`);
    if (Object.keys(have).length) return;                 // leave the file exactly as it is
  }
  const merged = { ...have, ...(got || {}) };
  // Merge, never truncate: anything git cannot see this time stays from the commit.
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, renderModule(merged));
  const added = Object.keys(merged).length - Object.keys(have).length;
  console.log(`emit-version-dates: ${Object.keys(merged).length} version date(s)${added > 0 ? ` (+${added} new)` : ''} → src/lib/version-dates.js`);
}

if (process.argv[1] && url.pathToFileURL(process.argv[1]).href === import.meta.url) {
  // NEVER exit non-zero. A cosmetic date must not be the reason a deploy fails.
  try { main(); } catch (e) { console.warn(`emit-version-dates: skipped (${e?.message || e})`); }
}
